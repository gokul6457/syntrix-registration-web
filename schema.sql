-- SYNTRIX Registration Table & Concurrency Enforcement
-- Run this script in Supabase Dashboard -> SQL Editor
-- ========================================================

-- 1. Create registrations table
CREATE TABLE IF NOT EXISTS public.registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name text NOT NULL,
    participant1_name text NOT NULL,
    participant1_regno text NOT NULL,
    participant1_department text NOT NULL,
    participant1_email text NOT NULL,
    participant1_phone text NOT NULL,
    participant2_name text,
    participant2_regno text,
    participant2_department text,
    participant2_email text,
    participant2_phone text,
    year_of_study text NOT NULL,
    system_preference text NOT NULL,
    payment_proof bytea,
    payment_proof_filename text,
    payment_proof_mimetype text,
    payment_status text NOT NULL DEFAULT 'Pending'
        CHECK (payment_status IN ('Pending', 'Verified', 'Rejected')),
    payment_rejection_reason text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 2. Create case-insensitive unique indexes
CREATE UNIQUE INDEX IF NOT EXISTS registrations_team_name_ci_unique
    ON public.registrations (upper(btrim(team_name)));

CREATE UNIQUE INDEX IF NOT EXISTS registrations_participant1_regno_ci_unique
    ON public.registrations (upper(btrim(participant1_regno)));

CREATE UNIQUE INDEX IF NOT EXISTS registrations_participant2_regno_ci_unique
    ON public.registrations (upper(btrim(participant2_regno)))
    WHERE participant2_regno IS NOT NULL;

-- 3. Row Level Security (RLS) - Restrict public access, allow service_role only
ALTER TABLE public.registrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.registrations FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.registrations_id_seq FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.registrations TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.registrations_id_seq TO service_role;

-- 4. Trigger function to enforce the 50-team limit and uniqueness
CREATE OR REPLACE FUNCTION public.enforce_registration_limits()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(632184730);

    IF (SELECT count(*) FROM public.registrations) >= 50 THEN
        RAISE EXCEPTION 'The event registration limit of 50 teams has been reached'
            USING ERRCODE = 'check_violation';
    END IF;

    IF nullif(btrim(NEW.participant2_regno), '') IS NOT NULL
       AND upper(btrim(NEW.participant1_regno)) = upper(btrim(NEW.participant2_regno)) THEN
        RAISE EXCEPTION 'A participant register number cannot be repeated within a team'
            USING ERRCODE = 'unique_violation';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.registrations AS existing
        WHERE upper(btrim(existing.team_name)) = upper(btrim(NEW.team_name))
           OR upper(btrim(existing.participant1_regno)) IN (
                upper(btrim(NEW.participant1_regno)),
                nullif(upper(btrim(NEW.participant2_regno)), '')
           )
           OR nullif(upper(btrim(existing.participant2_regno)), '') IN (
                upper(btrim(NEW.participant1_regno)),
                nullif(upper(btrim(NEW.participant2_regno)), '')
           )
    ) THEN
        RAISE EXCEPTION 'The team name or a participant register number is already registered'
            USING ERRCODE = 'unique_violation';
    END IF;

    RETURN NEW;
END;
$$;

-- 5. Attach the trigger to registrations table
DROP TRIGGER IF EXISTS registrations_enforce_limits ON public.registrations;
CREATE TRIGGER registrations_enforce_limits
    BEFORE INSERT ON public.registrations
    FOR EACH ROW
    EXECUTE FUNCTION public.enforce_registration_limits();
